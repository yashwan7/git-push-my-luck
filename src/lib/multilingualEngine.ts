/**
 * Returns fully localized Service Definition matching the active language.
 */
export function getLocalizedService(lang: SupportedLanguage, service: ServiceDefinition): ServiceDefinition {
  const serviceTrans = (SERVICE_TRANSLATIONS[lang] && SERVICE_TRANSLATIONS[lang][service.id]) ||
                       (SERVICE_TRANSLATIONS['en'] && SERVICE_TRANSLATIONS['en'][service.id]);

  if (!serviceTrans) {
    return service;
  }

  const translatedSteps: WorkflowStep[] = service.steps.map((step, idx) => {
    const stepTrans = serviceTrans.steps[idx];
    if (!stepTrans) return step;

    return {
      ...step,
      title: stepTrans.title || step.title,
      description: stepTrans.description || step.description,
      simplifiedDescription: stepTrans.simplifiedDescription || step.simplifiedDescription,
      fieldLabel: stepTrans.fieldLabel || step.fieldLabel,
      placeholder: stepTrans.placeholder || step.placeholder,
      helpText: stepTrans.helpText || step.helpText,
      audioPrompt: stepTrans.audioPrompt || step.audioPrompt,
      options: stepTrans.options ? stepTrans.options.map(opt => ({
        value: opt.value,
        label: opt.label,
      })) : step.options,
    };
  });

  return {
    ...service,
    title: serviceTrans.title || service.title,
    description: serviceTrans.description || service.description,
    organization: serviceTrans.organization || service.organization,
    badge: serviceTrans.badge || service.badge,
    standardDenseNotice: serviceTrans.standardDenseNotice || service.standardDenseNotice,
    steps: translatedSteps,
  };
}

/**
 * Returns fully localized Persona Preset matching the active language.
 */
export function getLocalizedPersona(lang: SupportedLanguage, persona: PersonaPreset): PersonaPreset {
  const personaTrans = (PERSONA_TRANSLATIONS[lang] && PERSONA_TRANSLATIONS[lang][persona.id]) ||
                       (PERSONA_TRANSLATIONS['en'] && PERSONA_TRANSLATIONS['en'][persona.id]);

  if (!personaTrans) {
    return persona;
  }

  return {
    ...persona,
    name: personaTrans.name || persona.name,
    tagline: personaTrans.tagline || persona.tagline,
    description: personaTrans.description || persona.description,
    badge: personaTrans.badge || persona.badge,
  };
}
